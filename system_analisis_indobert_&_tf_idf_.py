# ====================================================================
#  MENAMPILKAN HASIL PEMBOBOTAN TF-IDF
# ====================================================================

doc_index = 0

# Get all feature names and IDF values from the fitted vectorizer
all_terms = tfidf_vectorizer.get_feature_names_out()
all_idf_values = tfidf_vectorizer.idf_

# Get the TF-IDF vector for the specific document (doc_index) from X_train_tfidf
# This is a sparse row vector
doc_tfidf_vector_sparse = X_train_tfidf[doc_index]

# Get the indices of features (terms) that are present in this document (non-zero TF-IDF score)
# and their corresponding TF-IDF scores
feature_indices = doc_tfidf_vector_sparse.nonzero()[1]
tfidf_scores_for_doc = doc_tfidf_vector_sparse.data

# Extract the terms and their IDF values for only the features present in this document
terms_in_doc = [all_terms[i] for i in feature_indices]
idf_values_in_doc = [all_idf_values[i] for i in feature_indices]

# Calculate the 'TF' component for each term in the document
# If sublinear_tf is used, this 'TF' represents 1 + log(raw_term_frequency)
tf_values_in_doc = []
for i, tfidf_score in zip(feature_indices, tfidf_scores_for_doc):
    # Avoid division by zero, though idf_values_in_doc should be > 0 for actual features
    if all_idf_values[i] > 0:
        tf_values_in_doc.append(tfidf_score / all_idf_values[i])
    else:
        tf_values_in_doc.append(0.0) # Fallback

