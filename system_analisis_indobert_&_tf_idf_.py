def cleaning(text):

    text = re.sub(r'http\S+|www\.\S+', ' ', text)   # hapus URL
    text = re.sub(r'@\w+', ' ', text)               # hapus mention
    text = re.sub(r'#\w+', ' ', text)           # hapus hashtag (#)
    text = re.sub(r'[^a-zA-Z0-9\s.,!?]', ' ', text) # hapus simbol
    text = re.sub(r'\s+', ' ', text)                # hapus spasi berlebih
    text = re.sub(r'\d+', '', text)                 # Menghapus semua angka (0-9)
    text = re.sub(r'[^\w\s]', '', text)             # Menghapus tanda baca
    emoji_pattern = re.compile(                     # Menghapus emoji unicode
        "["
        u"\U0001F600-\U0001F64F"  # emoticon
        u"\U0001F300-\U0001F5FF"  # simbol & pictograph
        u"\U0001F680-\U0001F6FF"  # transport & map
        u"\U0001F1E0-\U0001F1FF"  # flags
        u"\U00002700-\U000027BF"
        u"\U000024C2-\U0001F251"
        "]+",
        flags=re.UNICODE
    )
    text = emoji_pattern.sub(r'', text)   # Menghapus emoticon teks (opsional)

    text = re.sub(r'[:;=8][\-o\*\\]?[)\]\(\[dDpP/\:\}\{@\|\\]', '', text)


    return text.strip()

