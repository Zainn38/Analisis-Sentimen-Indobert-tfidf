# ngram_range=(1, 2) membantu model memahami konteks (misal: "tidak enak")
# sublinear_tf=True meredam pengaruh kata yang muncul sangat sering (noise)
tfidf_vectorizer = TfidfVectorizer(
    ngram_range=(1, 2),
    sublinear_tf=True,
    max_features=10000 # Membatasi fitur agar tidak terlalu lebar
)

# Fit & Transform pada data Training
X_train_tfidf = tfidf_vectorizer.fit_transform(X_train_text)

