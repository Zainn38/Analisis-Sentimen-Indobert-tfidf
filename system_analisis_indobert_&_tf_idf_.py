# ====================================================================
# 3. EKSTRAKSI FITUR: INDOBERT DENGAN MEAN POOLING
# ====================================================================
tokenizer = AutoTokenizer.from_pretrained("indobenchmark/indobert-base-p1")
model_bert = AutoModel.from_pretrained("indobenchmark/indobert-base-p1")

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
model_bert.to(device)
model_bert.eval()

def indobert_embedding_optimized(text_list, max_len=128):
    embeddings = []
    for text in text_list:
        inputs = tokenizer(
            text,
            return_tensors="pt",
            truncation=True,
            padding='max_length',
            max_length=max_len
        )
        inputs = {k: v.to(device) for k, v in inputs.items()}

        with torch.no_grad():
            outputs = model_bert(**inputs)

        token_embeddings = outputs.last_hidden_state # [batch, seq_len, hidden_dim]
        mask = inputs['attention_mask'].unsqueeze(-1).expand(token_embeddings.size()).float()
        sum_embeddings = torch.sum(token_embeddings * mask, 1)
        sum_mask = torch.clamp(mask.sum(1), min=1e-9)
        mean_pooled = (sum_embeddings / sum_mask).cpu().numpy()

        embeddings.append(mean_pooled.flatten())

    return np.array(embeddings)

print("Sedang melakukan ekstraksi fitur IndoBERT (ini mungkin memakan waktu)...")
